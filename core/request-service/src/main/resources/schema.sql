DROP TABLE IF EXISTS REQUESTS CASCADE;

CREATE TABLE IF NOT EXISTS REQUESTS
(
    ID        BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    CREATED   TIMESTAMP WITHOUT TIME ZONE,
    EVENT     BIGINT                                  NOT NULL,
    REQUESTER BIGINT                                  NOT NULL,
    STATUS    VARCHAR(120)                            NOT NULL,

    CONSTRAINT PK_REQUEST
    PRIMARY KEY (ID),

    CONSTRAINT UQ_REQUEST_REQUESTER_EVENT
    UNIQUE (REQUESTER, EVENT)
    );

CREATE INDEX IF NOT EXISTS IDX_REQUEST_EVENT
    ON REQUESTS (EVENT);

CREATE INDEX IF NOT EXISTS IDX_REQUEST_REQUESTER
    ON REQUESTS (REQUESTER);

CREATE INDEX IF NOT EXISTS IDX_REQUEST_EVENT_STATUS
    ON REQUESTS (EVENT, STATUS);