DROP TABLE IF EXISTS COMPILATIONS_EVENTS CASCADE;
DROP TABLE IF EXISTS COMPILATIONS CASCADE;
DROP TABLE IF EXISTS EVENTS CASCADE;
DROP TABLE IF EXISTS LOCATIONS CASCADE;
DROP TABLE IF EXISTS CATEGORIES CASCADE;

CREATE TABLE IF NOT EXISTS CATEGORIES
(
    ID   BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    NAME VARCHAR(255)                            NOT NULL UNIQUE,

    CONSTRAINT PK_CATEGORY
    PRIMARY KEY (ID)
    );

CREATE TABLE IF NOT EXISTS LOCATIONS
(
    ID  BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    LAT DOUBLE PRECISION                        NOT NULL,
    LON DOUBLE PRECISION                        NOT NULL,

    CONSTRAINT PK_LOCATION
    PRIMARY KEY (ID)
    );

CREATE TABLE IF NOT EXISTS EVENTS
(
    ID                 BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    ANNOTATION         VARCHAR(2000),
    CATEGORY_ID        BIGINT,
    DESCRIPTION        TEXT,
    EVENT_DATE         TIMESTAMP WITHOUT TIME ZONE,
    CREATED_ON         TIMESTAMP WITHOUT TIME ZONE,
    INITIATOR_ID       BIGINT                                  NOT NULL,
    LOCATION_ID        BIGINT,
    PAID               BOOLEAN,
    PARTICIPANT_LIMIT  BIGINT,
    PUBLISHED_ON       TIMESTAMP WITHOUT TIME ZONE,
    REQUEST_MODERATION BOOLEAN,
    STATE              VARCHAR(120),
    TITLE              VARCHAR(120),

    CONSTRAINT PK_EVENT
    PRIMARY KEY (ID),

    CONSTRAINT EVENTS_CATEGORIES_ID_FK
    FOREIGN KEY (CATEGORY_ID)
    REFERENCES CATEGORIES (ID)
                                 ON DELETE CASCADE,

    CONSTRAINT EVENTS_LOCATIONS_ID_FK
    FOREIGN KEY (LOCATION_ID)
    REFERENCES LOCATIONS (ID)
                                 ON DELETE CASCADE
    );

CREATE TABLE IF NOT EXISTS COMPILATIONS
(
    ID     BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    PINNED BOOLEAN,
    TITLE  VARCHAR(550),

    CONSTRAINT PK_COMPILATION
    PRIMARY KEY (ID),

    CONSTRAINT UQ_COMPILATION_TITLE
    UNIQUE (TITLE)
    );

CREATE TABLE IF NOT EXISTS COMPILATIONS_EVENTS
(
    EVENT_ID       BIGINT NOT NULL,
    COMPILATION_ID BIGINT NOT NULL,

    CONSTRAINT PK_COMPILATIONS_EVENTS
    PRIMARY KEY (EVENT_ID, COMPILATION_ID),

    CONSTRAINT FK_COMPILATIONS_EVENTS_TO_COMPILATIONS
    FOREIGN KEY (COMPILATION_ID)
    REFERENCES COMPILATIONS (ID)
    ON DELETE CASCADE,

    CONSTRAINT FK_COMPILATIONS_EVENTS_TO_EVENTS
    FOREIGN KEY (EVENT_ID)
    REFERENCES EVENTS (ID)
    ON DELETE CASCADE
    );